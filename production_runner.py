from engine.article_full_generation_engine import ArticleFullGenerationEngine
import os
import sys

sys.path.append(os.path.dirname(os.path.abspath(__file__)))


def main():
    print("[+] جاري تشغيل محرك الأبحاث الطبية الاحترافي...")
    engine = ArticleFullGenerationEngine()

    # صياغة برومبت صارم لإنتاج مقال متكامل غني بالجداول والوسائط الهيكلية
    expert_prompt = """
    أعراض وطرق علاج التهاب الأمعاء عند الحيوانات الأليفة مع مراعاة الشروط الاحترافية التالية في مخرجات الـ HTML:
    1. اكتب مقالاً علمياً مطولاً جداً وشاملاً كافة التفاصيل الطبية والتشريحية الفسيولوجية.
    2. قم بتضمين جدول HTML متكامل ومنسق بوضوح (table) للمقارنة بين الأعراض الحادة والمزمنة ودرجات الخطورة.
    3. أضف أكواد تبيين نصية تشريحية وأماكن وضع الصور التشريحية باستخدام وسوم مناسبة مع تضمين توصيف دقيق للصورة التشريحية المطلوبة في سمة alt.
    4. ضع وسم فيديو توضيحي (Embed أو Placeholder) مخصص للمقالات الطبية لشرح التدخل الجراحي أو العلاجي.
    5. استخدم التنسيقات العلمية الجذابة والعناوين الفرعية (H2, H3, H4) وقوائم النقاط المنظمة.
    """

    print("[+] جاري توليد المقالة العلمية الشاملة...")
    try:
        # استخدام دالة التوليد الأساسية للمشروع
        result = engine.generate(expert_prompt)
        print("[+] تم توليد المقالة الاحترافية ورفعها إلى Blogger كمسودة بنجاح!")
        print(result)
    except Exception as e:
        print(f"[-] حدث خطأ أثناء تشغيل المحرك: {e}")


if __name__ == "__main__":
    main()
